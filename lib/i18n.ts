const patterns: [RegExp, (...values:string[])=>string][] = [
  [/^(AG-\d+) 장애 해제 · 자가진단 완료$/, id=>`${id} recovered · self-check passed`],
  [/^(\d+)건의 로그를 내보냈습니다\.$/, count=>`Exported ${count} log event${count==='1'?'':'s'}.`],
  [/^(\d+)번 로그 상세$/, id=>`Details for log ${id}`],
  [/^(\d+)개 단말기 점검 필요$/, count=>`${count} device${count==='1'?'':'s'} need attention`],
  [/^(AG-\d+) (정상|장애|Normal|Fault) 단말기 선택$/, (id,status)=>`Select ${id} · ${status==='정상'||status==='Normal'?'normal':'fault'}`],
  [/^(AG-\d+) 통신 장애 주입 완료\. 카드를 태그하고 로그를 확인하세요\.$/, id=>`${id}: network fault injected. Tap a card and inspect the logs.`],
  [/^(\d+) \/ (\d+) 테스트 통과$/, (passed,total)=>`${passed} / ${total} tests passed`],
];

export function translate(language:Language,text:string):string {
  if(language==='ko')return text;
  const key=text.trim();
  const translated=english[key]??patterns.reduce<string|undefined>((result,[pattern,render])=>{
    if(result!==undefined)return result;
    const match=key.match(pattern);return match?render(...match.slice(1)):undefined;
  },undefined);
  if(translated===undefined)return text;
  return text.slice(0,text.length-text.trimStart().length)+translated+text.slice(text.trimEnd().length);
}
